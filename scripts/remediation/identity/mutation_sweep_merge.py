"""Mutation sweep for the duplicate merge and the parent lanes: every guard must be able to fail.

The machinery is `mechanical/mutation_sweep.py`'s (a case counts as FIRED only when its needle occurs
exactly once, the mutant compiles, the named test passed on the unmutated file and is reported
FAILED against the mutant - anything else fails the sweep). The cases are this package's: one per guard
of the row lane (`mechanical/rowlane.py`), the lane family in `mechanical/lane.py` (the move, retire and
parent lanes), the planners (`dup_merge.py`, `parent.py`), the two question stages (`dup_judge.py`,
`parent_judge.py`, `label_rounds.py`) and the calibration sets (`pair_calibration.py`), each naming the one test
that must notice.

A guard that is an `if` is found by its line: `at()` reads the file, takes the `nth` line equal to
`line` and extends it by the lines that follow until the needle occurs exactly once, so a repeated
`if row is None:` is told apart by what comes after it. The mutant is that `if` with its condition
replaced by `False` (`mutation_sweep.falsify`). Anything that is not an `if` is a `swap()` with its
exact text.

Run it from a parent process on a clean committed tree, never from inside a subagent lane (a lane
killed between applying a mutation and restoring it leaves the mutant behind):

    ./.venv/Scripts/python.exe scripts/remediation/identity/mutation_sweep_merge.py            # all
    ./.venv/Scripts/python.exe scripts/remediation/identity/mutation_sweep_merge.py rowlane     # by label

`git status` must be clean afterwards: the sweep restores every file and checks its sha256.
"""

