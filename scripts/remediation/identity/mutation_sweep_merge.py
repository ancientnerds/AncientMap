def _falsified(needle: str) -> str:
    """`falsify` for an `if`, and the same for an `elif` (the condition becomes `False`)."""
    first, sep, rest = needle.partition("\n")
    if first.strip().startswith("elif ") and first.strip().endswith(":"):
        indent = first[: len(first) - len(first.lstrip(" "))]
        return f"{indent}elif False:{sep}{rest}"
    return falsify(needle)


def at(label: str, path: Path, line: str, test: str, testfile: str, nth: int = 0) -> Case:
    """The `if` (or `elif`) guard on the `nth` line equal to `line`, with its condition made `False`."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    found = [i for i, candidate in enumerate(lines) if candidate == line]
    if len(found) <= nth:
        raise ValueError(f"{label}: {path.name} has {len(found)} line(s) {line!r}, not {nth + 1}")
    start = found[nth]
    for width in range(1, 12):
        needle = "\n".join(lines[start : start + width])
        if text.count(needle) == 1:
            return Case(label, path, needle, _falsified(needle), test, testfile)
    raise ValueError(f"{label}: no unique needle starting at line {start + 1} of {path.name}")


def swap(label: str, path: Path, old: str, new: str, test: str, testfile: str) -> Case:
    return Case(label, path, old, new, test, testfile)


